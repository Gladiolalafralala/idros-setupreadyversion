async function seed() {
  console.log("\n🔥  IDROS v2.5 — Malolos CDRRMO 2026 Real Data");
  console.log("    Loading " + INCIDENTS.length + " actual dispatch records...\n");

  console.log("👤  Creating users...");
  for (const u of USERS) {
    try {
      await createUserWithEmailAndPassword(auth, u.email, u.password);
      console.log("    ✓  " + u.email);
    } catch (e) {
      if (e.code === "auth/email-already-in-use") {
        console.log("    –  " + u.email + " (already exists)");
      } else { console.error("    ✗  " + e.message); }
    }
  }

  console.log("\n🚑  Seeding fleet...");
  for (const a of AMBULANCES) { await addDoc(collection(db, "ambulances"), a); }
  console.log("    ✓  " + AMBULANCES.length + " vehicles");

  console.log("\n🧑‍⚕️  Seeding personnel...");
  for (const o of OPERATORS) { await addDoc(collection(db, "operators"), o); }
  console.log("    ✓  " + OPERATORS.length + " personnel");

  console.log("\n💉  Seeding interventions...");
  for (const i of INTERVENTIONS) { await addDoc(collection(db, "system_interventions"), i); }
  console.log("    ✓  " + INTERVENTIONS.length + " interventions");

  console.log("\n📋  Loading incidents...");
  let count = 0;
  for (const inc of INCIDENTS) {
    const { id, ...data } = inc;
    await addDoc(collection(db, "incidents"), { ...data, id });
    count++;
    if (count % 50 === 0) console.log("    ... " + count + "/" + INCIDENTS.length);
  }

  console.log("\n✅  Done! " + INCIDENTS.length + " real 2026 CDRRMO incidents loaded.");
  console.log("\n  Login: admin@malolos.gov.ph / idros2025");
  console.log("");
  process.exit(0);
}

seed().catch(e => { console.error("Failed:", e.message); process.exit(1); });
